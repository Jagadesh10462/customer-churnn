CREATE OR REPLACE VIEW CUSTOMER_CHURN_TRAINING AS
SELECT AGE,GENDER,INCOME,PURCHASE_FREQUENCY,AVERAGE_ORDER_VALUE,
       TOTAL_SPEND,CUSTOMER_LIFETIME_MONTHS,CHURN
FROM CUSTOMER_DATA;

CREATE OR REPLACE SNOWFLAKE.ML.CLASSIFICATION CUSTOMER_CHURN_MODEL(
    INPUT_DATA => SYSTEM$REFERENCE(
        'VIEW',
        'CUSTOMER_CHURN_DB.ML_SCHEMA.CUSTOMER_CHURN_TRAINING'
    ),
    TARGET_COLNAME => 'CHURN'
);

CALL CUSTOMER_CHURN_MODEL!SHOW_EVALUATION_METRICS();

-- Prediction input
CREATE OR REPLACE VIEW CUSTOMER_CHURN_PREDICT_INPUT AS
SELECT AGE,GENDER,INCOME,PURCHASE_FREQUENCY,AVERAGE_ORDER_VALUE,
       TOTAL_SPEND,CUSTOMER_LIFETIME_MONTHS
FROM CUSTOMER_DATA;

-- Prediction output
CREATE OR REPLACE TABLE CUSTOMER_CHURN_PREDICTIONS AS
SELECT
    CUSTOMER_ID, AGE, GENDER, INCOME, PURCHASE_FREQUENCY,
    AVERAGE_ORDER_VALUE, TOTAL_SPEND, CUSTOMER_LIFETIME_MONTHS,
    CHURN AS ACTUAL_CHURN,
    CUSTOMER_CHURN_MODEL!PREDICT(
        OBJECT_CONSTRUCT(
            'AGE', AGE,
            'GENDER', GENDER,
            'INCOME', INCOME,
            'PURCHASE_FREQUENCY', PURCHASE_FREQUENCY,
            'AVERAGE_ORDER_VALUE', AVERAGE_ORDER_VALUE,
            'TOTAL_SPEND', TOTAL_SPEND,
            'CUSTOMER_LIFETIME_MONTHS', CUSTOMER_LIFETIME_MONTHS
        )
    ) AS PREDICTION
FROM CUSTOMER_DATA;

CREATE OR REPLACE VIEW CHURN_DASHBOARD AS
SELECT
    CUSTOMER_ID, AGE, GENDER, INCOME, PURCHASE_FREQUENCY,
    AVERAGE_ORDER_VALUE, TOTAL_SPEND, CUSTOMER_LIFETIME_MONTHS,
    ACTUAL_CHURN,
    PREDICTION:class::VARCHAR AS PREDICTED_CHURN,
    PREDICTION:probability:"0"::FLOAT AS NO_CHURN_PROBABILITY,
    PREDICTION:probability:"1"::FLOAT AS CHURN_PROBABILITY
FROM CUSTOMER_CHURN_PREDICTIONS;

SELECT * FROM CHURN_DASHBOARD ORDER BY CHURN_PROBABILITY DESC;
