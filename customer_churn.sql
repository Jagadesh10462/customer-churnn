-- Customer Churn Prediction using Snowflake ML
-- Demo project: end-to-end setup, training, evaluation and prediction

CREATE DATABASE IF NOT EXISTS CUSTOMER_CHURN_DB;
USE DATABASE CUSTOMER_CHURN_DB;

CREATE SCHEMA IF NOT EXISTS ML_SCHEMA;
USE SCHEMA ML_SCHEMA;

CREATE WAREHOUSE IF NOT EXISTS ML_WH
WITH WAREHOUSE_SIZE='X-SMALL'
AUTO_SUSPEND=60
AUTO_RESUME=TRUE;

USE WAREHOUSE ML_WH;

CREATE OR REPLACE TABLE CUSTOMER_DATA (
    CUSTOMER_ID NUMBER,
    AGE NUMBER,
    GENDER VARCHAR,
    INCOME FLOAT,
    PURCHASE_FREQUENCY FLOAT,
    AVERAGE_ORDER_VALUE FLOAT,
    TOTAL_SPEND FLOAT,
    CUSTOMER_LIFETIME_MONTHS NUMBER,
    CHURN NUMBER
);

